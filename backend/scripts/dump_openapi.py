def _literal(value: object) -> str:
    """A TypeScript literal for ``value``: a whole float prints as an integer, a list or a
    mapping as a readonly literal. A mapping keeps the backend's order, which the frontend
    shows (the snapshot host list)."""
    if isinstance(value, float) and value.is_integer():
        value = int(value)
    text = json.dumps(value, indent=2)
    return f"{text} as const" if isinstance(value, (list, tuple, dict)) else text


def constants_module() -> str:
    lines = [HEADER]
    for name, value in sorted(frontend_constants().items()):
        assert re.fullmatch(r"[A-Z][A-Z0-9_]*", name), name
        lines.append(f"export const {name} = {_literal(value)};")
    return "\n".join(lines) + "\n"


def main() -> None:
    Path(sys.argv[1]).write_text(json.dumps(app.openapi(), indent=2, sort_keys=True) + "\n")
    Path(sys.argv[2]).write_text(constants_module())


if __name__ == "__main__":
    main()
