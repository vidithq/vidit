/** A 1x1 GIF of `frames` frames, each behind a graphic control extension, after a comment block,
 *  with a local colour table on the last frame, so a walk of its blocks meets every kind. */
export function tinyGif(frames: number): Uint8Array<ArrayBuffer> {
  const bytes = [
    ...Array.from("GIF89a", (c) => c.charCodeAt(0)),
    0x01, 0x00, 0x01, 0x00, 0x80, 0x00, 0x00,
    0x00, 0x00, 0x00, 0xff, 0xff, 0xff,
    0x21, 0xfe, 0x03, 0x61, 0x62, 0x63, 0x00,
  ];
  for (let i = 0; i < frames; i++) {
    const local = i === frames - 1;
    bytes.push(0x21, 0xf9, 0x04, 0x00, 0x0a, 0x00, 0x00, 0x00);
    bytes.push(0x2c, 0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x01, 0x00, local ? 0x80 : 0x00);
    if (local) bytes.push(0x00, 0x00, 0x00, 0xff, 0xff, 0xff);
    bytes.push(0x02, 0x02, 0x44, 0x01, 0x00);
  }
  bytes.push(0x3b);
  return new Uint8Array(bytes);
}
